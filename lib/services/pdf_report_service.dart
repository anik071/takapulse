class CategoryBreakdown {
  final String name;
  final String subtitle;
  final double amount;
  final int transactionCount;
  final double percentage;
  final String iconKey;
  final int colorValue;

  const CategoryBreakdown({
    required this.name,
    required this.subtitle,
    required this.amount,
    required this.transactionCount,
    required this.percentage,
    required this.iconKey,
    required this.colorValue,
  });
}

class GeneratedPdfInfo {
  final File file;
  final String fileName;
  final String sizeLabel;

  const GeneratedPdfInfo({
    required this.file,
    required this.fileName,
    required this.sizeLabel,
  });
}

class PdfReportService {
  PdfReportService._();
  static final PdfReportService instance = PdfReportService._();

  static const String monthEndTaskName = 'takapulse_month_end_pdf_task';
  static const String _lastAutoGeneratedKey = 'last_auto_pdf_month';

  /// Groups a month's expense transactions by module/category for charts & PDF
  List<CategoryBreakdown> computeCategoryBreakdowns(
    List<ExpenseTransaction> transactions,
    double totalOutflow,
  ) {
    final expenses =
        transactions.where((t) => t.type == ModuleType.expense).toList();
    if (expenses.isEmpty) return [];

    final Map<String, List<ExpenseTransaction>> grouped = {};
    for (final tx in expenses) {
      grouped.putIfAbsent(tx.title, () => []).add(tx);
    }

    final palette = [
      0xFFFF4D6D, // Rose Coral
      0xFFA855F7, // Purple
      0xFF00EEFC, // Cyan
      0xFFFBBF24, // Amber
      0xFF47F3BB, // Mint
    ];

    int colorIdx = 0;
    final list = grouped.entries.map((entry) {
      final sum = entry.value.fold<double>(0, (acc, item) => acc + item.amount);
      final pct = totalOutflow > 0 ? (sum / totalOutflow) * 100 : 0.0;
      final first = entry.value.first;
      final assignedColor = palette[colorIdx % palette.length];
      colorIdx++;

      return CategoryBreakdown(
        name: entry.key,
        subtitle: '${entry.value.length} Transactions',
        amount: sum,
        transactionCount: entry.value.length,
        percentage: pct,
        iconKey: first.iconKey,
        colorValue: assignedColor,
      );
    }).toList();

    list.sort((a, b) => b.amount.compareTo(a.amount));
    return list;
  }

  /// Builds and saves a formatted monthly PDF report from local SQLite records
  Future<GeneratedPdfInfo> generateMonthlyStatementPdf(
    DateTime targetMonth,
  ) async {
    final monthKey = DateFormat('yyyy-MM').format(targetMonth);
    final monthTitle = DateFormat('MMMM yyyy').format(targetMonth);
    final shortCode = DateFormat('MMM_yyyy').format(targetMonth);

    final db = DatabaseService.instance;
    final summary = await db.getMonthlySummary(monthKey);
    final transactions = await db.getTransactionsForMonth(monthKey);
    final breakdowns =
        computeCategoryBreakdowns(transactions, summary.totalOutflow);

    final pdf = pw.Document(
      title: 'TakaPulse Statement - $monthTitle',
      author: 'TakaPulse Personal Vault',
    );

    final moneyFmt = NumberFormat('#,##,##0.00', 'en_US');

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) => [
          // Header Banner
          pw.Container(
            padding: const pw.EdgeInsets.all(18),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromHex('#101320'),
              borderRadius: pw.BorderRadius.circular(12),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'TakaPulse Financial Statement',
                      style: pw.TextStyle(
                        color: PdfColor.fromHex('#47F3BB'),
                        fontSize: 18,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text(
                      'Billing Period: $monthTitle',
                      style: const pw.TextStyle(
                        color: PdfColors.white,
                        fontSize: 11,
                      ),
                    ),
                  ],
                ),
                pw.Container(
                  padding: const pw.EdgeInsets.symmetric(
                    horizontal: 10,
                    vertical: 5,
                  ),
                  decoration: pw.BoxDecoration(
                    color: PdfColor.fromHex('#06D6A0'),
                    borderRadius: pw.BorderRadius.circular(6),
                  ),
                  child: pw.Text(
                    'MONTHLY AUDIT',
                    style: pw.TextStyle(
                      color: PdfColor.fromHex('#002116'),
                      fontSize: 9,
                      fontWeight: pw.FontWeight.bold,
                    ),
                  ),
                ),
              ],
            ),
          ),
          pw.SizedBox(height: 18),

          // Summary KPI Strip
          pw.Row(
            children: [
              _pdfKpiBox(
                'Total Earning (Inflow)',
                'BDT ${moneyFmt.format(summary.totalInflow)}',
                PdfColor.fromHex('#006C4F'),
              ),
              pw.SizedBox(width: 10),
              _pdfKpiBox(
                'Total Spending (Outflow)',
                'BDT ${moneyFmt.format(summary.totalOutflow)}',
                PdfColor.fromHex('#9B0031'),
              ),
              pw.SizedBox(width: 10),
              _pdfKpiBox(
                'Net Balance',
                'BDT ${moneyFmt.format(summary.netBalance)}',
                PdfColor.fromHex('#004F54'),
              ),
            ],
          ),
          pw.SizedBox(height: 20),

          // Module Breakdown Section
          pw.Text(
            'Spending Composition by Module',
            style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 8),
          if (breakdowns.isEmpty)
            pw.Text(
              'No expense entries recorded for $monthTitle.',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            )
          else
            pw.TableHelper.fromTextArray(
              headerStyle: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
                fontSize: 10,
              ),
              headerDecoration: pw.BoxDecoration(
                color: PdfColor.fromHex('#1C1F2D'),
              ),
              cellStyle: const pw.TextStyle(fontSize: 10),
              cellAlignment: pw.Alignment.centerLeft,
              headers: ['Module / Segment', 'Entries', 'Share', 'Total (BDT)'],
              data: breakdowns
                  .map(
                    (b) => [
                      b.name,
                      '${b.transactionCount}',
                      '${b.percentage.toStringAsFixed(1)}%',
                      moneyFmt.format(b.amount),
                    ],
                  )
                  .toList(),
            ),
          pw.SizedBox(height: 22),

          // Full Itemized Ledger Table
          pw.Text(
            'Itemized Transaction Ledger (${transactions.length} records)',
            style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 8),
          if (transactions.isEmpty)
            pw.Text(
              'No transactions logged during this period.',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            )
          else
            pw.TableHelper.fromTextArray(
              headerStyle: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
                fontSize: 9,
              ),
              headerDecoration: pw.BoxDecoration(
                color: PdfColor.fromHex('#1C1F2D'),
              ),
              cellStyle: const pw.TextStyle(fontSize: 9),
              headers: ['Date', 'Module', 'Note / Channel', 'Type', 'Amount'],
              data: transactions.map((tx) {
                final isInc = tx.type == ModuleType.income;
                return [
                  DateFormat('dd MMM yyyy, hh:mm a').format(tx.timestamp),
                  tx.title,
                  tx.channelOrNote,
                  isInc ? 'EARNING' : 'SPENDING',
                  '${isInc ? '+' : '-'} ${moneyFmt.format(tx.amount)}',
                ];
              }).toList(),
            ),
        ],
        footer: (context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(top: 12),
          child: pw.Text(
            'Generated by TakaPulse • Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
          ),
        ),
      ),
    );

    final docsDir = await getApplicationDocumentsDirectory();
    final statementsDir = Directory(p.join(docsDir.path, 'statements'));
    if (!await statementsDir.exists()) {
      await statementsDir.create(recursive: true);
    }

    final fileName = 'TakaPulse_Statement_$shortCode.pdf';
    final file = File(p.join(statementsDir.path, fileName));
    final bytes = await pdf.save();
    await file.writeAsBytes(bytes, flush: true);

    final kb = (bytes.length / 1024).ceil();
    return GeneratedPdfInfo(
      file: file,
      fileName: fileName,
      sizeLabel: '$kb KB',
    );
  }

  pw.Widget _pdfKpiBox(String label, String value, PdfColor accent) {
    return pw.Expanded(
      child: pw.Container(
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: PdfColors.grey300),
          borderRadius: pw.BorderRadius.circular(8),
        ),
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              label,
              style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              value,
              style: pw.TextStyle(
                fontSize: 12,
                fontWeight: pw.FontWeight.bold,
                color: accent,
              ),
            ),
          ],
        ),
      ),
    );
  }

  /// Shares the generated monthly PDF via WhatsApp, Email, or OS Share Sheet
  Future<void> shareStatementPdf(
    DateTime month, {
    String? channelHint,
  }) async {
    final info = await generateMonthlyStatementPdf(month);
    final monthTitle = DateFormat('MMMM yyyy').format(month);

    await Share.shareXFiles(
      [XFile(info.file.path, mimeType: 'application/pdf')],
      subject: 'TakaPulse Monthly Expense Sheet - $monthTitle',
      text: channelHint != null
          ? 'Attached is my $monthTitle expense & bill statement ($channelHint).'
          : 'Attached is my $monthTitle expense & bill statement from TakaPulse.',
    );
  }

  /// Checks if a new calendar month has started and auto-generates last month's PDF
  Future<GeneratedPdfInfo?> checkAndRunMonthEndExport() async {
    final now = DateTime.now();
    final previousMonth = DateTime(now.year, now.month - 1, 1);
    final prevKey = DateFormat('yyyy-MM').format(previousMonth);

    final prefs = await SharedPreferences.getInstance();
    final alreadyGenerated = prefs.getString(_lastAutoGeneratedKey);
    if (alreadyGenerated == prevKey) return null;

    final info = await generateMonthlyStatementPdf(previousMonth);
    await prefs.setString(_lastAutoGeneratedKey, prevKey);
    return info;
  }
}

/// Top-level callback for Workmanager background scheduling
@pragma('vm:entry-point')
void callbackDispatcher() {
  Workmanager().executeTask((task, inputData) async {
    if (task == PdfReportService.monthEndTaskName) {
      await PdfReportService.instance.checkAndRunMonthEndExport();
    }
    return Future.value(true);
  });
}